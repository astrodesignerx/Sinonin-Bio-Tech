/**
 * Generates tiny base64 previews for cover images so <Image placeholder="blur">
 * has something to show while the full file decodes. Re-run after adding or
 * replacing any cover.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const DIRS = ["public/images/reports", "public/images/blog", "public/images/stories"];
const out = {};

for (const dir of DIRS) {
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".webp"))) {
    const abs = path.join(dir, file);
    const buf = await sharp(abs).resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
    out[`/${dir.replace(/^public\//, "")}/${file}`] =
      `data:image/webp;base64,${buf.toString("base64")}`;
  }
}

const body = `// GENERATED by scripts/gen-blur-placeholders.mjs. Do not edit by hand.
export const BLUR: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync("src/lib/blur-data.ts", body);
console.log(`wrote ${Object.keys(out).length} placeholders, ${(body.length / 1024).toFixed(0)}KB`);
